function readRaw(): string | null {
  try { return localStorage.getItem(STORAGE_KEY); } catch { return null; }
}

function write(db: Db): void {
  const raw = JSON.stringify(db);
  try {
    localStorage.setItem(STORAGE_KEY, raw);
  } catch {
    throw new StorageFullError();
  }
  cache = { raw, db };
}

export class StorageFullError extends Error {
  constructor() { super("Espace de stockage du navigateur plein : supprimez des images (logo, photos) ou exportez puis réinitialisez les données."); }
}

/** Base courante (relue si un autre onglet l'a modifiée). Créée au premier lancement. */
export async function getDb(): Promise<Db> {
  const raw = readRaw();
  if (raw && cache && cache.raw === raw) return cache.db;
  if (raw) {
    try {
      const db = JSON.parse(raw) as Db;
      if (db && db.version === 1) { cache = { raw, db }; return db; }
    } catch { /* base illisible : on repart d'une base neuve */ }
  }
  // Premier lancement : une seule création même si plusieurs requêtes arrivent en même temps
  seeding ??= seed().then(db => { write(db); return db; }).finally(() => { seeding = null; });
  return seeding;
}
let seeding: Promise<Db> | null = null;

/**
 * Exécute `fn` sur une copie de la base et l'enregistre seulement si tout a réussi.
 * `fn` peut lever une erreur : la base reste alors inchangée.
 */
export function transaction<T>(fn: (db: Db) => T | Promise<T>): Promise<T> {
  // Les transactions passent une par une : deux requêtes simultanées ne peuvent pas s'écraser
  const run = queue.then(async () => {
    const current = await getDb();
    const draft = structuredClone(current);
    const result = await fn(draft);
    if (JSON.stringify(draft) !== cache?.raw) write(draft);
    return result;
  });
  queue = run.then(() => undefined, () => undefined);
  return run;
}
let queue: Promise<void> = Promise.resolve();

/** Identifiant suivant d'une table (jamais réutilisé, même après suppression). */
export function nextId(db: Db, table: string): number {
  db.seq[table] = (db.seq[table] ?? 0) + 1;
  return db.seq[table];
}

// ───────────────────────── Sauvegarde / restauration (page Paramètres) ─────────────────────────
export async function exportData(): Promise<string> {
  const db = await getDb();
  // Les jetons de session ne font pas partie de la sauvegarde
  return JSON.stringify({ ...db, tokens: [] }, null, 2);
}

export function importData(json: string): void {
  const db = JSON.parse(json) as Db;
  if (!db || db.version !== 1 || !Array.isArray(db.users) || !Array.isArray(db.products)) {
    throw new Error("Fichier de sauvegarde invalide.");
  }
  write({ ...db, tokens: [] });
}

export function resetData(): void {
  try { localStorage.removeItem(STORAGE_KEY); } catch { /* ignoré */ }
  cache = null;
}
