/** Équivalent de backend/app/Http/Support/Present.php : mêmes formes JSON que l'API Laravel. */
import type {
  Db, ProductRow, SaleRow, SaleReturnRow, PurchaseRow, CustomerRow, SupplierRow, RoleRow, UserRow, LossRow,
  InventoryItemRow, PendingRow, NotificationRow, SettingsRow, StockMovementRow, PromotionRow, CashSessionRow,
} from "./db";
import { isoDate } from "./db";

const s = (n: number | null | undefined) => (n === null || n === undefined ? null : String(n));
const userName = (db: Db, id: number | null | undefined) => db.users.find(u => u.id === id)?.name;

export const product = (db: Db, p: ProductRow) => ({
  id: String(p.id), name: p.name, category: db.categories.find(c => c.id === p.categoryId)?.name ?? "",
  price: p.price, cost: p.cost, taxRate: p.taxRate, stock: p.stock, minStock: p.minStock, unit: p.unit,
  barcode: p.barcode || null, expiryDate: p.expiryDate,
});

export const saleReturn = (db: Db, r: SaleReturnRow, withSale = true) => ({
  id: String(r.id), returnNo: r.returnNo, saleId: String(r.saleId),
  invoiceNo: withSale ? (db.sales.find(x => x.id === r.saleId)?.invoiceNo ?? "—") : null,
  userName: userName(db, r.userId) ?? "—", date: r.date, total: r.total, taxAmount: r.taxAmount,
  creditReduction: r.creditReduction, cashRefund: r.cashRefund, refundMethod: r.refundMethod, restocked: r.restocked, reason: r.reason,
  items: r.items.map(i => ({ name: i.name, quantity: i.quantity, unitValue: i.unitValue, total: i.total })),
});

export const sale = (db: Db, x: SaleRow, withReturns = true) => ({
  id: String(x.id), invoiceNo: x.invoiceNo,
  items: x.items.map(i => ({
    id: String(i.id), productId: String(i.productId), name: i.name, quantity: i.quantity, price: i.price, cost: i.cost, total: i.total,
    taxRate: i.taxRate, taxAmount: i.taxAmount, discountPercent: i.discountPercent, discountAmount: i.discountAmount,
    promotionLabel: i.promotionLabel, returnedQuantity: i.returnedQuantity,
  })),
  total: x.total, taxRate: x.taxRate, taxAmount: x.taxAmount, paid: x.paid, change: x.change,
  amountPaid: x.amountPaid, balanceDue: x.balanceDue, returnedTotal: x.returnedTotal,
  paymentStatus: x.balanceDue <= 0.004 ? "paid" : x.amountPaid <= 0.004 ? "unpaid" : "partial",
  customerId: s(x.customerId), customerName: db.customers.find(c => c.id === x.customerId)?.name ?? null,
  userId: String(x.userId), userName: userName(db, x.userId) ?? "—", date: x.date, paymentMethod: x.paymentMethod, createdAt: x.createdAt,
  returns: withReturns ? db.saleReturns.filter(r => r.saleId === x.id).map(r => saleReturn(db, r, false)) : [],
});

export const purchase = (db: Db, p: PurchaseRow) => ({
  id: String(p.id), reference: p.reference,
  items: p.items.map(i => ({
    productId: i.productId ? String(i.productId) : "", name: i.name, quantity: i.quantity, price: i.price, total: i.total,
    taxRate: i.taxRate, priceTtc: i.priceTtc, totalTtc: i.totalTtc,
  })),
  total: p.total, totalHt: p.totalHt, totalTax: p.totalTax, supplierId: String(p.supplierId),
  supplierName: db.suppliers.find(x => x.id === p.supplierId)?.name ?? "—", date: p.date, managerName: userName(db, p.userId) ?? "—",
});

export const customer = (db: Db, c: CustomerRow) => ({
  id: String(c.id), name: c.name, phone: c.phone ?? "", email: c.email ?? "", address: c.address ?? "",
  totalPurchases: c.totalPurchases, creditLimit: c.creditLimit,
  balance: Math.round(db.sales.filter(x => x.customerId === c.id).reduce((a, x) => a + x.balanceDue, 0) * 100) / 100,
  createdAt: c.createdAt,
});

export const supplier = (x: SupplierRow) => ({
  id: String(x.id), name: x.name, contact: x.contact ?? "", phone: x.phone ?? "", email: x.email ?? "", address: x.address ?? "",
});

export const role = (r: RoleRow) => ({
  id: String(r.id), name: r.name, slug: r.slug, description: r.description ?? "", permissions: [...r.permissions], isSystem: r.isSystem, createdAt: r.createdAt,
});

export const user = (u: UserRow, withAvatar = true) => ({
  id: String(u.id), name: u.name, email: u.email, phone: u.phone ?? "", role: String(u.roleId),
  avatar: withAvatar ? (u.avatar || null) : null, active: u.active, createdAt: u.createdAt, lastSeen: u.lastSeen,
});

export const loss = (db: Db, l: LossRow) => ({
  id: String(l.id), productId: l.productId ? String(l.productId) : "", productName: l.productName, quantity: l.quantity,
  unitPrice: l.unitPrice, total: l.total, reason: l.reason, date: l.date,
  notedBy: userName(db, l.notedBy) ?? (l.autoGenerated ? "Système" : "—"), autoGenerated: l.autoGenerated,
});

export const inventoryRow = (db: Db, i: InventoryItemRow) => {
  const session = db.inventorySessions.find(x => x.id === i.sessionId);
  return {
    id: String(i.id), productId: i.productId ? String(i.productId) : "", productName: i.productName,
    expected: i.expected, actual: i.actual, difference: Math.round((i.actual - i.expected) * 1000) / 1000,
    date: session?.date ?? null, period: session?.period ?? null, sessionId: String(i.sessionId),
    userName: userName(db, session?.userId) ?? null,
  };
};

export const pending = (db: Db, a: PendingRow) => ({
  id: String(a.id), kind: a.kind, module: a.module, action: a.action, description: a.description,
  details: a.details ?? {}, payload: a.payload ?? {}, requestedBy: String(a.requestedBy),
  requestedByName: userName(db, a.requestedBy) ?? "—", date: a.date, status: a.status,
  reviewedBy: s(a.reviewedBy), reviewedByName: userName(db, a.reviewedBy) ?? null,
  reviewedDate: a.reviewedAt ? a.reviewedAt.slice(0, 10) : null, rejectReason: a.rejectReason,
});

export const notification = (n: NotificationRow, readIds: number[]) => ({
  id: String(n.id), userId: n.userId ? String(n.userId) : "*", title: n.title, message: n.message, type: n.type,
  date: n.notifiedAt, read: readIds.includes(n.id), scope: n.scope,
  triggeredById: n.triggeredById ? String(n.triggeredById) : "system", triggeredByName: n.triggeredByName,
  targetPage: n.targetPage, targetId: n.targetId,
});

export const settings = (x: SettingsRow) => ({ ...x });

export const stockMovement = (m: StockMovementRow) => ({
  id: String(m.id), productId: s(m.productId), productName: m.productName, userName: m.userName ?? "Système", type: m.type,
  quantity: m.quantity, stockBefore: m.stockBefore, stockAfter: m.stockAfter, reason: m.reason,
  referenceType: m.referenceType, referenceId: s(m.referenceId), referenceLabel: m.referenceLabel, date: m.createdAt,
});

export const isRunning = (p: PromotionRow, date: string) =>
  p.active && (!p.startsOn || p.startsOn <= date) && (!p.endsOn || p.endsOn >= date);

export const promotion = (db: Db, p: PromotionRow) => ({
  id: String(p.id), name: p.name, type: p.type, value: p.value, scope: p.scope,
  categoryId: s(p.categoryId), categoryName: db.categories.find(c => c.id === p.categoryId)?.name ?? null,
  productId: s(p.productId), productName: db.products.find(x => x.id === p.productId)?.name ?? null,
  minQuantity: p.minQuantity, startsOn: p.startsOn, endsOn: p.endsOn, active: p.active, running: isRunning(p, isoDate()),
});

export const cashSession = (db: Db, c: CashSessionRow, summary: ReturnType<typeof import("./services").cashSummary>) => ({
  id: String(c.id), userId: String(c.userId), userName: userName(db, c.userId) ?? "—", status: c.status,
  openedAt: c.openedAt, closedAt: c.closedAt, openingFloat: c.openingFloat,
  expectedCash: c.status === "closed" ? c.expectedCash : summary.expectedCash,
  countedCash: c.countedCash, difference: c.difference, note: c.note, summary,
});
